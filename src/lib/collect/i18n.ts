export const COLLECT_DICT: Record<UiLang, CollectDict> = { en, ar };

export function statusLabel(t: CollectDict, status: string): string {
  return (t as unknown as Record<string, string>)[`status_${status}`] ?? status;
}

export function intentLabel(t: CollectDict, intent: string | null | undefined): string {
  if (!intent) return "";
  return (t as unknown as Record<string, string>)[`intent_${intent}`] ?? intent;
}

export function stepLabel(t: CollectDict, step: string | null): string {
  if (!step) return "";
  return (t as unknown as Record<string, string>)[`step_${step}`] ?? step;
}
